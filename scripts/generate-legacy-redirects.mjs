#!/usr/bin/env node
// Generate static-host redirect artifacts from old-url-map.csv.
// Caddy gets a 301 snippet; Netlify/Cloudflare Pages get a _redirects file.
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const CSV = path.join(ROOT, "old-url-map.csv");
const BLOG = path.join(ROOT, "src/content/blog");
const DEPLOY = path.join(ROOT, "deploy");
const CADDY = path.join(DEPLOY, "legacy-redirects.caddy");
const NETLIFY = path.join(ROOT, "public", "_redirects");

const lines = fs.readFileSync(CSV, "utf8").trim().split(/\r?\n/);
if (lines.shift() !== "old_url,new_url,title") {
  throw new Error("old-url-map.csv header must be old_url,new_url,title");
}

const rows = lines.map((line) => {
  const match = line.match(/^([^,]+),([^,]+),/);
  if (!match) throw new Error(`bad CSV row: ${line}`);
  const [, from, to] = match;
  if (!from.startsWith("/post/") || !to.startsWith("/blog/") || !to.endsWith("/")) {
    throw new Error(`unexpected redirect: ${from} -> ${to}`);
  }
  return { from, to };
});

const unique = new Set(rows.map((r) => r.from));
if (unique.size !== rows.length) throw new Error("duplicate old URL in old-url-map.csv");
if (rows.length === 0) throw new Error("old-url-map.csv has no redirects");

const blogSlugs = new Set(
  fs.readdirSync(BLOG).filter((name) => fs.existsSync(path.join(BLOG, name, "index.md")))
);
for (const { to } of rows) {
  const slug = to.slice("/blog/".length, -1);
  if (!blogSlugs.has(slug)) throw new Error(`redirect target missing: ${to}`);
}

fs.mkdirSync(DEPLOY, { recursive: true });
const caddy = [
  "# Generated by `pnpm redirects` from old-url-map.csv. Do not edit by hand.",
  "# Include this file inside the imshane.site site block:",
  "#   import legacy-redirects.caddy",
  "",
  ...rows.map(({ from, to }) => `redir ${from} ${to} permanent`),
  "",
].join("\n");
fs.writeFileSync(CADDY, caddy);

const netlify = [
  "# Generated by `pnpm redirects` from old-url-map.csv. Do not edit by hand.",
  ...rows.map(({ from, to }) => `${from} ${to} 301`),
  "",
].join("\n");
fs.writeFileSync(NETLIFY, netlify);

console.log(`generated ${rows.length} redirects`);
console.log(`  ${path.relative(ROOT, CADDY)}`);
console.log(`  ${path.relative(ROOT, NETLIFY)}`);
